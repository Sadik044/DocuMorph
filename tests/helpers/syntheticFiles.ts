export async function createSyntheticPdf(
  pageCount: number,
  title: string = 'TestDocument'
): Promise<File> {
  const doc = await PDFDocument.create();
  for (let i = 0; i < pageCount; i++) {
    const page = doc.addPage([500, 700]);
    page.drawText(`${title} - Page ${i + 1}`);
  }
  const bytes = await doc.save();
  return new File([bytes.buffer as ArrayBuffer], `${title}.pdf`, {
    type: 'application/pdf',
  });
}

export function createSyntheticJpg(name: string = 'photo.jpg'): File {
  return new File([SYNTHETIC_JPG_BYTES.buffer as ArrayBuffer], name, {
    type: 'image/jpeg',
  });
}

export function createSyntheticPng(name: string = 'graphic.png'): File {
  return new File([SYNTHETIC_PNG_BYTES.buffer as ArrayBuffer], name, {
    type: 'image/png',
  });
}

/**
 * Creates a synthetic scanned PDF containing only an embedded raster image and zero selectable text.
 */
export async function createScannedPdf(title: string = 'ScannedDocument'): Promise<File> {
  const doc = await PDFDocument.create();
  const jpg = await doc.embedJpg(SYNTHETIC_JPG_BYTES);
  const page = doc.addPage([500, 700]);
  page.drawImage(jpg, { x: 50, y: 50, width: 400, height: 600 });
  const bytes = await doc.save();
  return new File([bytes.buffer as ArrayBuffer], `${title}.pdf`, {
    type: 'application/pdf',
  });
}
